/** 토크나이즈된 쿼리 배열에 동의어 확장을 적용한 새 배열 반환 (2-hop) */
export function expandTerms(terms: string[]): string[] {
  const expanded = new Set(terms)
  // 1단계: 원본 terms의 동의어
  const firstHop: string[] = []
  for (const term of terms) {
    for (const syn of SYNONYM_MAP[term] ?? []) {
      if (!expanded.has(syn)) { expanded.add(syn); firstHop.push(syn) }
    }
  }
  // 2단계: 1단계에서 추가된 동의어의 동의어 (BUG4 fix: 2-hop 확장)
  for (const term of firstHop) {
    for (const syn of SYNONYM_MAP[term] ?? []) {
      expanded.add(syn)
    }
  }

  // 날짜 토큰 확장: 0-패딩 숫자가 있으면 MMDD 조합도 생성
  const paddedNums = terms.filter(t => /^\d{2}$/.test(t))
  if (paddedNums.length >= 2) {
    for (let i = 0; i < paddedNums.length; i++) {
      const mm = parseInt(paddedNums[i], 10)
      if (mm < 1 || mm > 12) continue
      for (let j = 0; j < paddedNums.length; j++) {
        if (i === j) continue
        const dd = parseInt(paddedNums[j], 10)
        if (dd < 1 || dd > 31) continue
        expanded.add(`${paddedNums[i]}${paddedNums[j]}`)
      }
    }
  }
  return [...expanded]
}
